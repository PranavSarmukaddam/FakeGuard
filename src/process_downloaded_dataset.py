def append_curated_to_csv(csv_path: str, records: list):
    """Append curated (title, text, subject) records to an existing CSV."""
    fieldnames = ["title", "text", "subject", "date"]
    with open(csv_path, "a", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        for title, text, subject in records:
            w.writerow({"title": title, "text": text, "subject": subject, "date": ""})


def count_rows(csv_path: str) -> int:
    with open(csv_path, "r", encoding="utf-8", errors="ignore") as f:
        return sum(1 for _ in csv.reader(f)) - 1  # subtract header


